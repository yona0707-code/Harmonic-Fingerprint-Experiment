-- Run this file once in the Supabase SQL editor.
create table if not exists public.participants (
    participant_id uuid primary key,
    created_at timestamptz not null default now(),
    age_range text not null,
    grew_up_countries text not null,
    current_country text not null,
    music_training_years text not null,
    musical_activities text[] not null,
    music_genres text[] not null,
    other_music_genre text,
    weekly_listening_hours text not null,
    current_mood text not null,
    hearing_difficulty text not null,
    recruitment_source text not null,
    other_recruitment_source text,
    listening_device text not null,
    most_tense_sound text,
    preferred_sound text,
    overall_association text
);

create table if not exists public.responses (
    response_id bigint generated by default as identity primary key,
    participant_id uuid not null references public.participants(participant_id),
    trial_number integer not null,
    audio_filename text not null,
    pleasantness integer not null,
    relaxation integer not null,
    tension integer not null,
    emotion text not null,
    other_emotion text,
    written_association text,
    created_at timestamptz not null default now(),
    constraint responses_participant_trial_unique unique (participant_id, trial_number)
);

alter table public.participants enable row level security;
alter table public.responses enable row level security;

-- Table privileges and RLS both apply. Grant only the operation the public app
-- needs; PostgreSQL owners and Supabase service roles retain administrative access.
revoke all on table public.participants from anon, authenticated;
revoke all on table public.responses from anon, authenticated;
grant insert on table public.participants to anon, authenticated;
grant insert on table public.responses to anon, authenticated;
grant usage on sequence public.responses_response_id_seq to anon, authenticated;

create policy "Public app can insert participants"
on public.participants for insert to anon, authenticated with check (true);

create policy "Public app can insert responses"
on public.responses for insert to anon, authenticated with check (true);

-- Intentionally no SELECT, UPDATE, or DELETE policies are created.

-- Keep the participant row and all four responses atomic. A failed request is
-- fully rolled back, which makes the participant-facing retry button safe.
create or replace function public.save_completed_experiment(
    p_participant jsonb,
    p_responses jsonb
)
returns void
language plpgsql
security invoker
set search_path = ''
as $$
begin
    if jsonb_typeof(p_responses) <> 'array'
       or jsonb_array_length(p_responses) <> 4 then
        raise exception 'A completed experiment requires exactly four responses';
    end if;

    insert into public.participants (
        participant_id, age_range, grew_up_countries, current_country,
        music_training_years, musical_activities, music_genres,
        other_music_genre, weekly_listening_hours, current_mood,
        hearing_difficulty, recruitment_source, other_recruitment_source,
        listening_device, most_tense_sound, preferred_sound, overall_association
    ) values (
        (p_participant->>'participant_id')::uuid,
        p_participant->>'age_range',
        p_participant->>'grew_up_countries',
        p_participant->>'current_country',
        p_participant->>'music_training_years',
        array(select jsonb_array_elements_text(p_participant->'musical_activities')),
        array(select jsonb_array_elements_text(p_participant->'music_genres')),
        p_participant->>'other_music_genre',
        p_participant->>'weekly_listening_hours',
        p_participant->>'current_mood',
        p_participant->>'hearing_difficulty',
        p_participant->>'recruitment_source',
        p_participant->>'other_recruitment_source',
        p_participant->>'listening_device',
        p_participant->>'most_tense_sound',
        p_participant->>'preferred_sound',
        p_participant->>'overall_association'
    );

    insert into public.responses (
        participant_id, trial_number, audio_filename, pleasantness,
        relaxation, tension, emotion, other_emotion, written_association
    )
    select
        (p_participant->>'participant_id')::uuid,
        item.trial_number,
        item.audio_filename,
        item.pleasantness,
        item.relaxation,
        item.tension,
        item.emotion,
        item.other_emotion,
        item.written_association
    from jsonb_to_recordset(p_responses) as item(
        participant_id uuid,
        trial_number integer,
        audio_filename text,
        pleasantness integer,
        relaxation integer,
        tension integer,
        emotion text,
        other_emotion text,
        written_association text
    );
end;
$$;

revoke all on function public.save_completed_experiment(jsonb, jsonb) from public;
grant execute on function public.save_completed_experiment(jsonb, jsonb)
to anon, authenticated;
